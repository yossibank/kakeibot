@Composable
internal fun HideButton(
    isHidden: Boolean,
    onSelect: () -> Unit,
) {
    Text(
        text = if (isHidden) "表示する" else "非表示",
        modifier = Modifier
            .height(40.dp)
            .clip(CircleShape)
            .background(Palette.card)
            .border(
                width = 1.dp,
                color = Palette.accent.opacity(Emphasis.Muted),
                shape = CircleShape,
            ).clickable(onClick = onSelect)
            .padding(
                horizontal = 14.dp,
                vertical = 10.dp,
            ),
        color = Palette.accent,
        style = textFont(
            size = FontSize.Small,
            weight = FontWeight.SemiBold,
        ),
    )
}

